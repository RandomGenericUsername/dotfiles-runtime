#!/usr/bin/env python3
"""contract-pin-check -- vendored generated bindings match `contracts/generated/`.

WHY THIS GATE EXISTS (spine AD-6, REQ-004). The event contract is canonical in
the `contracts` repo, which generates `generated/contract.py`, `generated/
contract.ts` and `generated/events.schema.json`. dotfiles-v3 VENDORS the Python
binding and the JSON Schema (committed copies, not a submodule) so the runtime
can consume them without a cross-repo build step. The TypeScript binding is no
longer vendored here: the bar now deploys whole from the pinned `ags-apps` unit,
and its `contract.ts` pin half lives in `ags-apps`. A vendored copy is a second
source of truth the moment someone hand-edits it -- exactly the drift AD-6 exists
to prevent. This gate diffs each vendored copy against the `contracts` repo's
`generated/` artifact and FAILS on any difference, so an edit that is not a
regeneration is caught here rather than at runtime.

WHAT IS COMPARED, AND WHY A HEADER IS NOT A LOOPHOLE. Each vendored file is the
`contracts` artifact with a fixed three-line vendored header prepended (the
header names the source and the pinned commit). The gate reconstructs the
expected file as `header(pin) + generated bytes` and compares byte-for-byte, so
a hand-edit to EITHER the header or the generated body fails. The header is not
stripped-and-ignored; it is part of the expected content. The pin itself is read
from `CONTRACT_PIN`, so the header and the pin file must agree.

JSON CANNOT CARRY A COMMENT HEADER. `events.schema.json` is vendored as the
EXACT `contracts` bytes (no header): a JSON document has no comment syntax, and
a sidecar or an injected `$comment` would make the copy differ from the artifact
the gate diffs against. Its entry uses an empty header, so the comparison is the
raw byte-for-byte diff -- still a tamper check, just with nothing to prepend. The
pin for it lives in `CONTRACT_PIN` (shared with the header-carrying copies).

THE PIN IS A COMMIT, NOT A SUBMODULE. `CONTRACTS_REPO` names the sibling
checkout (default: `../contracts` beside this repo). When that directory is
absent the gate SKIPS with a clear message and exits 0: the contracts repo is a
sibling checkout that CI for THIS repo does not have, and a pin gate that hard-
failed without it would be red for every clone that is not sitting next to the
contracts repo. A missing `generated/` INSIDE a present contracts repo is a
failure, not a skip -- that is a misconfigured pin, not an absent one.

Usage:  python3 scripts/contract-pin-check.py [--repo-root DIR] [--contracts-repo DIR]
Env:    CONTRACTS_REPO   path to the contracts checkout (default below)
Exit:   0 = vendored copies match (or the contracts repo is absent -> skip)
        1 = a mismatch, a missing pin file, or a misconfigured contracts repo
"""

from __future__ import annotations

import argparse
import difflib
import os
import sys
from collections.abc import Callable
from pathlib import Path

DEFAULT_CONTRACTS_REPO = str(
    Path(__file__).resolve().parents[1].parent / "contracts"
)

#: Repo-relative paths. The gate locates the repo from its own `__file__` (like
#: `ci-gates-parity.py`), so its CWD does not matter.
#:
#: The Python binding lives in the `domain` layer: it is pure data (no I/O) that
#: the domain, ports and adapters all consume, and the hexagon only lets `domain`
#: be imported by every layer (ports/adapters may not import each other). See
#: `tests/architecture/test_layering.py`.
PY_VENDORED = Path("src/runtime/domain/contract_generated.py")
#: The generated JSON Schema is a resource read by an adapter (file I/O), so it
#: lives in `adapters/` beside the runtime's other embedded schemas.
SCHEMA_VENDORED = Path("src/runtime/adapters/contract_generated.schema.json")
PIN_FILE = Path("src/runtime/adapters/CONTRACT_PIN")


def _py_header(pin: str) -> bytes:
    """The fixed header prepended to the vendored Python binding.

    Kept in the gate, not only in the file: this is the golden prefix the gate
    reconstructs the expected copy from, so the header cannot drift silently.
    """
    return (
        "# VENDORED — DO NOT EDIT.\n"
        f"# GENERATED from the `contracts` repo (generated/contract.py) at pin {pin}.\n"
        "# Source of truth: contracts/event-contract.{xml,json}. Verify: `make contract-pin-check`.\n"
    ).encode("utf-8")


def _json_header(pin: str) -> bytes:
    """No header for the vendored JSON Schema (JSON has no comment syntax).

    The vendored copy is the EXACT `contracts/generated/events.schema.json`
    bytes; the gate's `header(pin) + bytes` reconstruction reduces to the raw
    artifact, and the pin is recorded in `CONTRACT_PIN`.
    """
    return b""


#: (vendored path relative to the repo root, filename under `generated/`, header).
VENDORED: tuple[tuple[Path, str, Callable[[str], bytes]], ...] = (
    (PY_VENDORED, "contract.py", _py_header),
    (SCHEMA_VENDORED, "events.schema.json", _json_header),
)


def read_pin(repo_root: Path) -> str:
    """Return the pinned contracts commit recorded in the pin file."""
    return (repo_root / PIN_FILE).read_text(encoding="utf-8").strip()


def _diff_message(vendored_rel: Path, actual: bytes, expected: bytes) -> str:
    """A bounded unified diff naming the first lines that differ."""
    actual_lines = actual.decode("utf-8", errors="replace").splitlines(keepends=True)
    expected_lines = expected.decode("utf-8", errors="replace").splitlines(keepends=True)
    diff = list(
        difflib.unified_diff(
            actual_lines,
            expected_lines,
            fromfile=f"vendored: {vendored_rel}",
            tofile="expected: contracts/generated + vendored header",
            n=1,
        )
    )
    shown = "".join(diff[:40])
    if len(diff) > 40:
        shown += f"... ({len(diff) - 40} more diff line(s))\n"
    return f"{vendored_rel}: hand-edited or off-pin\n{shown.rstrip()}"


def check(repo_root: Path, contracts_repo: Path, pin: str) -> list[str]:
    """Return human-readable mismatches (empty == every vendored copy is exact)."""
    errors: list[str] = []
    generated_dir = contracts_repo / "generated"
    for vendored_rel, generated_name, header in VENDORED:
        vendored_path = repo_root / vendored_rel
        generated_path = generated_dir / generated_name
        if not vendored_path.is_file():
            errors.append(f"vendored copy missing: {vendored_rel}")
            continue
        if not generated_path.is_file():
            errors.append(
                f"contracts artifact missing: {generated_path} "
                f"(CONTRACTS_REPO is present but its generated/ is incomplete)"
            )
            continue
        expected = header(pin) + generated_path.read_bytes()
        actual = vendored_path.read_bytes()
        if actual != expected:
            errors.append(_diff_message(vendored_rel, actual, expected))
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="vendored contract bindings match contracts/generated")
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="dotfiles-v3 repo root (default: parent of scripts/)",
    )
    parser.add_argument(
        "--contracts-repo",
        type=Path,
        default=None,
        help="contracts checkout (default: $CONTRACTS_REPO or the pinned sibling path)",
    )
    args = parser.parse_args(argv)

    repo_root: Path = args.repo_root
    contracts_repo: Path = args.contracts_repo or Path(
        os.environ.get("CONTRACTS_REPO", DEFAULT_CONTRACTS_REPO)
    )

    if not contracts_repo.is_dir():
        print(
            f"contract-pin-check: SKIP — contracts repo not found at {contracts_repo} "
            f"(set CONTRACTS_REPO to enable this gate)"
        )
        return 0

    try:
        pin = read_pin(repo_root)
    except FileNotFoundError:
        print(f"contract-pin-check: FAIL — pin file missing: {PIN_FILE}")
        return 1
    if not pin:
        print(f"contract-pin-check: FAIL — pin file is empty: {PIN_FILE}")
        return 1

    errors = check(repo_root, contracts_repo, pin)
    if errors:
        print(f"contract-pin-check: FAIL — {len(errors)} vendored copy mismatch(es):")
        for error in errors:
            print(f"  - {error}")
        print(
            "  Fix: regenerate in `contracts` (`make generate`), re-vendor, or undo the "
            "hand-edit. Do not silence this gate."
        )
        return 1

    print(
        f"contract-pin-check: PASS — vendored bindings match "
        f"{contracts_repo}/generated at pin {pin}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
